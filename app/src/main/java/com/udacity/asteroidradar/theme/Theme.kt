/**
 * System contrast level requested by the user
 * (Settings ▸ Accessibility ▸ Color and motion ▸ Contrast level, Android 14+).
 */
enum class ContrastLevel { Standard, Medium, High }

/**
 * Maps the raw platform contrast value to a [ContrastLevel].
 *
 * [UiModeManager.getContrast] returns a float in `[-1, 1]`: the system picker emits
 * `0.0` (standard), `0.5` (medium) and `1.0` (high). Midpoint thresholds make the
 * mapping robust to OEMs that use slightly different values.
 */
private fun Float.toContrastLevel(): ContrastLevel = when {
    this >= 0.75f -> ContrastLevel.High
    this >= 0.25f -> ContrastLevel.Medium
    else -> ContrastLevel.Standard
}

/**
 * Observes the system contrast level.
 *
 * `Configuration` has no contrast field and `uiMode` has no contrast flag, so the
 * source of truth is [UiModeManager.getContrast] (API 34+). [LocalConfiguration]
 * is used as a re-read key so that any configuration change (night mode, locale,
 * returning from Settings, etc.) refreshes the value. A [UiModeManager.ContrastChangeListener]
 * also pushes live updates without needing an Activity recreation.
 * Below API 34 (and in Previews) this always returns [ContrastLevel.Standard].
 */
@Composable
fun rememberSystemContrastLevel(): ContrastLevel {
    val view = LocalView.current
    if (view.isInEditMode || Build.VERSION.SDK_INT < Build.VERSION_CODES.UPSIDE_DOWN_CAKE) {
        return ContrastLevel.Standard
    }
    return rememberSystemContrastLevelApi34()
}

@RequiresApi(Build.VERSION_CODES.UPSIDE_DOWN_CAKE)
@Composable
private fun rememberSystemContrastLevelApi34(): ContrastLevel {
    val context = LocalContext.current
    val configuration = LocalConfiguration.current
    val uiModeManager = remember(context) { context.getSystemService(UiModeManager::class.java) }

    var contrast by remember(configuration, uiModeManager) {
        mutableFloatStateOf(uiModeManager?.contrast ?: 0f)
    }

    DisposableEffect(uiModeManager) {
        if (uiModeManager == null) return@DisposableEffect onDispose { }
        val listener = UiModeManager.ContrastChangeListener { newContrast -> contrast = newContrast }
        uiModeManager.addContrastChangeListener(context.mainExecutor, listener)
        onDispose { uiModeManager.removeContrastChangeListener(listener) }
    }

    return contrast.toContrastLevel()
}

@Composable
fun AsteroidRadarTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Dynamic color is available on Android 12+ (and already honours the system contrast level)
    dynamicColor: Boolean = false,
    contrastLevel: ContrastLevel = rememberSystemContrastLevel(),
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> when (contrastLevel) {
            ContrastLevel.High -> highContrastDarkColorScheme
            ContrastLevel.Medium -> mediumContrastDarkColorScheme
            ContrastLevel.Standard -> DarkColorScheme
        }

        else -> when (contrastLevel) {
            ContrastLevel.High -> highContrastLightColorScheme
            ContrastLevel.Medium -> mediumContrastLightColorScheme
            ContrastLevel.Standard -> LightColorScheme
        }
    }

    // Edge-to-edge: the system bars are transparent (see enableEdgeToEdge() in the Activity),
    // so we only pick the icon color based on what is actually drawn behind each bar:
    //  - status bar sits over the primary-colored TopAppBar
    //  - navigation bar sits over the background
    // Luminance-based selection stays correct for every contrast scheme and dynamic color.
    val view = LocalView.current
    if (!view.isInEditMode) {
        val darkStatusBarIcons = colorScheme.primary.luminance() > 0.5f
        val darkNavigationBarIcons = colorScheme.background.luminance() > 0.5f
        SideEffect {
            val window = (view.context as? Activity)?.window ?: return@SideEffect
            WindowCompat.getInsetsController(window, view).apply {
                isAppearanceLightStatusBars = darkStatusBarIcons
                isAppearanceLightNavigationBars = darkNavigationBarIcons
            }
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        shapes = Shapes,
        content = content
    )
}
